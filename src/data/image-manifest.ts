/**
 * Fork & Founders — Image Manifest
 * ---------------------------------
 * Single source of truth for every visual asset shipped with the website.
 * Mirrors the `imageAsset` Sanity schema so each record can be imported into
 * the CMS without re-keying. See /docs/asset-register.md for the prose register.
 *
 * Rules enforced across all entries:
 *  - No remote placeholder services (Unsplash / Picsum / placehold / hotlinks).
 *  - No invented people, clients, investors, platform logos or skyline clichés.
 *  - All AI-generated masters were post-processed locally (watermark strip
 *    removed, responsive crops, WebP q80–85).
 */

export type ImageAssetType = 'hero' | 'editorial' | 'og' | 'poster' | 'icon' | 'logo'
export type ImageSourceType = 'ai-generated' | 'client-supplied' | 'licensed-stock' | 'ui-component'
export type ApprovalStatus = 'approved-internal' | 'pending-client-review' | 'pending-client-supply'

export interface ImageManifestEntry {
  /** Stable identifier used by CMS relationships and the asset register */
  id: string
  /** File name including extension */
  filename: string
  /** Public path served by the site */
  path: string
  /** Primary page(s) where the asset is used */
  page: string
  /** Section or component slot */
  section: string
  type: ImageAssetType
  width: number
  height: number
  /** File size in KB (build-time snapshot) */
  sizeKb: number
  /** Accessibility alt text (EN) */
  alt: string
  /** Arabic alt text — populated during AR content phase */
  altAr: string | null
  sourceType: ImageSourceType
  approvalStatus: ApprovalStatus
  /** CMS document id this asset relates to (imageAsset._id / referencing doc) */
  cmsRelationship: string
  /** Replacement expected from the client? */
  expectsClientReplacement: boolean
}

